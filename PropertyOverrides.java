import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.Map;
import java.util.Properties;
import java.util.TreeMap;

/** Merge a properties file with explicitly namespaced environment overrides. */
public final class PropertyOverrides {
    private static final String PREFIX = "ONTOP_PROPERTY_";
    private static final String TIMEOUT = "ontop.query.defaultTimeout";

    public static void main(String[] args) {
        try {
            generate(args.length == 0 ? "" : args[0]);
        } catch (Exception error) {
            // Do not log property values, which may contain credentials.
            System.err.println("Cannot generate Ontop runtime properties: " + error.getMessage());
            System.exit(1);
        }
    }

    private static void generate(String source) throws Exception {
        Properties properties = new Properties();
        if (!source.isEmpty()) {
            try (InputStream input = Files.newInputStream(Path.of(source))) {
                properties.load(input);
            }
        }
        properties.putIfAbsent(TIMEOUT, "120");
        for (Map.Entry<String, String> entry : new TreeMap<>(System.getenv()).entrySet()) {
            if (!entry.getKey().startsWith(PREFIX)) {
                continue;
            }
            String key = entry.getKey().substring(PREFIX.length()).replace("__", ".");
            if (key.isEmpty()) {
                throw new IllegalArgumentException("ONTOP_PROPERTY_ requires a property name");
            }
            properties.setProperty(key, entry.getValue());
        }
        try {
            if (Integer.parseInt(properties.getProperty(TIMEOUT)) < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException error) {
            throw new IllegalArgumentException(TIMEOUT + " must be a non-negative integer in seconds (0 disables it)");
        }
        Path directory = Path.of(System.getenv().getOrDefault("TMPDIR", "/tmp"));
        Path output = Files.createTempFile(directory, "ontop-runtime-", ".properties",
                                          PosixFilePermissions.asFileAttribute(
                                              PosixFilePermissions.fromString("rw-------")));
        try {
            try (OutputStream stream = Files.newOutputStream(output)) {
                properties.store(stream, "Generated by ontop-fork; original properties are unchanged");
            }
        } catch (Exception error) {
            Files.deleteIfExists(output);
            throw error;
        }
        // Only the path is printed; the shell wrapper consumes it.
        System.out.println(output);
    }
}
